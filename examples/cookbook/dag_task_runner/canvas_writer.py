def render_canvas_source(state: RunState) -> str:
    payload = asdict(state)
    state_literal = json.dumps(payload, indent=2)
    return f"{HEADER}\n\nconst STATE: RunState = {state_literal};\n\n{BODY}\n"


class CanvasWriter:
    def __init__(self, canvas_path: str, debounce_ms: int = 200) -> None:
        self.canvas_path = canvas_path
        self.debounce_ms = debounce_ms
        self._pending: RunState | None = None
        self._timer: threading.Timer | None = None
        self._lock = threading.Lock()
        self._last_error: BaseException | None = None

    def schedule(self, state: RunState) -> None:
        with self._lock:
            self._pending = clone_state(state)
            if self._timer is not None:
                return
            self._timer = threading.Timer(self.debounce_ms / 1000, self._flush_timer)
            self._timer.daemon = True
            self._timer.start()

    def _flush_timer(self) -> None:
        with self._lock:
            self._timer = None
            snapshot = self._pending
            self._pending = None
        if snapshot is not None:
            self._write_now(snapshot)

    def flush(self) -> None:
        with self._lock:
            if self._timer is not None:
                self._timer.cancel()
                self._timer = None
            snapshot = self._pending
            self._pending = None
        if snapshot is not None:
            self._write_now(snapshot)
        if self._last_error is not None:
            raise self._last_error

    def _write_now(self, state: RunState) -> None:
        try:
            path = Path(self.canvas_path)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(render_canvas_source(state), encoding="utf-8")
            self._last_error = None
        except BaseException as exc:
            self._last_error = exc
            raise
