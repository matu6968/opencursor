from __future__ import annotations

import json
import threading
from collections.abc import Callable
from copy import deepcopy
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any, Literal

from cookbook.dag_task_runner.dag import Complexity, DAG

TaskStatus = Literal["PENDING", "RUNNING", "FINISHED", "ERROR"]


@dataclass
class TaskState:
    id: str
    depends_on: list[str]
    complexity: Complexity
    subtask_prompt: str
    status: TaskStatus
    model: str
    startedAt: int | None = None
    finishedAt: int | None = None
    resultText: str | None = None
    errorMessage: str | None = None
    inputTokens: int | None = None
    outputTokens: int | None = None
    durationMs: int | None = None


@dataclass
class RunState:
    title: str
    startedAt: int
    tasks: list[TaskState]
    finishedAt: int | None = None
    runOutcome: Literal["SUCCESS", "FAILED", "INTERRUPTED"] | None = None
    runMessage: str | None = None


def initial_run_state(dag: DAG, model_for: Callable[[Complexity], str]) -> RunState:
    return RunState(
        title=dag.title,
        startedAt=__import__("time").time_ns() // 1_000_000,
        tasks=[
            TaskState(
                id=task.id,
                depends_on=list(task.depends_on),
                complexity=task.complexity,
                subtask_prompt=task.subtask_prompt,
                status="PENDING",
                model=model_for(task.complexity),
            )
            for task in dag.tasks
        ],
    )


def clone_state(state: RunState) -> RunState:
    return RunState(
        title=state.title,
        startedAt=state.startedAt,
        finishedAt=state.finishedAt,
        runOutcome=state.runOutcome,
        runMessage=state.runMessage,
        tasks=[deepcopy(task) if not isinstance(task, TaskState) else TaskState(**asdict(task)) for task in state.tasks],
    )


